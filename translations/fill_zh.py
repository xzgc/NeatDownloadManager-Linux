tree = ET.parse('translations/neatdm_zh.ts')
root = tree.getroot()
filled = missing = 0
for msg in root.iter('message'):
    src = msg.find('source')
    if src is None or src.text is None:
        continue
    key = src.text
    tr = msg.find('translation')
    if key in ZH:
        tr.text = ZH[key]
        tr.attrib.pop('type', None)
        filled += 1
    else:
        if tr.get('type') == 'unfinished':
            missing += 1
            print('untranslated:', repr(key))
tree.write('translations/neatdm_zh.ts', encoding='utf-8', xml_declaration=True)
print(f'filled={filled} missing={missing}')
